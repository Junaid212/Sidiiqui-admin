'use strict';
/**
 * Keeps the public website's prerendered article pages (<PUBLIC_SITE_ROOT>/blogs/<slug>/index.html) in step
 * with the database, WITHOUT a full site build.
 *
 *  - syncArticle():   called right after a successful save/publish/unpublish/delete of ONE article.
 *  - reconcileAll():  compares every article with its page and repairs differences. This is also the retry
 *                     mechanism: anything that failed earlier is picked up by the next run.
 *  - startSweep():    runs reconcileAll() on a timer (also publishes scheduled articles when their time arrives).
 *
 * Safety rules:
 *  - Opt-in: does nothing unless PUBLIC_SITE_ROOT is set. When disabled it reports "skipped", never "updated".
 *  - Only ever writes <root>/blogs/<valid-slug>/index.html. Slugs are validated; paths are checked to stay inside.
 *  - Atomic writes (temp file + rename), then the file is READ BACK and verified before "updated" is reported.
 *  - Only deletes pages that were generated by this system (marker or the old build-script signature).
 *  - reconcileAll() never deletes anything if the database read failed or returned no articles.
 *  - Never throws to the caller of syncArticle(): failures are returned, logged, and retried by the sweep.
 */
const fs = require('fs/promises');
const path = require('path');
const core = require('./blogPrerenderCore.cjs');

// ── configuration ───────────────────────────────────────────────────────────────────────────────────────
function getConfig(env = process.env) {
    const root = env.PUBLIC_SITE_ROOT ? path.resolve(env.PUBLIC_SITE_ROOT) : null;
    const hosts = new Set();
    try { if (env.SUPABASE_URL) hosts.add(new URL(env.SUPABASE_URL).hostname.toLowerCase()); } catch { /* ignore */ }
    String(env.PRERENDER_IMAGE_HOSTS || '').split(',').map((h) => h.trim().toLowerCase()).filter(Boolean).forEach((h) => hosts.add(h));
    return {
        enabled: !!root,
        root,
        templatePath: root ? path.resolve(env.PRERENDER_TEMPLATE_PATH || path.join(root, 'index.html')) : null,
        imageHosts: [...hosts],
    };
}

// ── module state ────────────────────────────────────────────────────────────────────────────────────────
const dimsCache = new Map();
let chain = Promise.resolve();       // serialises all file work (no two writes race)
let lastSync = null;                 // summary of the most recent reconcile run
const failures = new Map();          // slug -> { error, at }   (cleared when a later run succeeds)
let sweepTimer = null; let sweeping = false;

const withLock = (fn) => { const run = chain.then(fn, fn); chain = run.catch(() => {}); return run; };

function friendlyError(err) {
    const code = err && err.code;
    if (code === 'EACCES' || code === 'EPERM') return 'Permission denied writing to the public site folder';
    if (code === 'ENOENT') return 'Public site folder or page template not found';
    if (code === 'ENOSPC') return 'No space left on the server';
    // Any other file-system error: report the code only. Messages from Node include full server paths, which must never reach a client.
    if (typeof code === 'string' && /^E[A-Z]+$/.test(code)) return `Could not write to the public site folder (${code}). Check the PUBLIC_SITE_ROOT configuration.`;
    return String((err && err.message) || err || 'unknown error').slice(0, 160);
}

// ── paths ───────────────────────────────────────────────────────────────────────────────────────────────
function pagePaths(cfg, slug) {
    if (!core.isValidSlug(slug)) throw new Error(`Invalid slug "${String(slug).slice(0, 40)}"`);
    const blogsDir = path.join(cfg.root, 'blogs');
    const dir = path.join(blogsDir, slug);
    const file = path.join(dir, 'index.html');
    const rel = path.relative(blogsDir, file);
    if (rel.startsWith('..') || path.isAbsolute(rel)) throw new Error('Refusing to write outside the blogs folder');
    return { blogsDir, dir, file };
}

const readIfExists = async (file) => { try { return await fs.readFile(file, 'utf8'); } catch (e) { if (e.code === 'ENOENT') return null; throw e; } };

async function writeAtomic(file, content) {
    await fs.mkdir(path.dirname(file), { recursive: true, mode: 0o755 });
    const tmp = `${file}.tmp-${process.pid}-${Date.now()}`;
    try {
        await fs.writeFile(tmp, content, { encoding: 'utf8', mode: 0o644 });
        await fs.rename(tmp, file);
        await fs.chmod(file, 0o644).catch(() => {});
    } catch (e) { await fs.unlink(tmp).catch(() => {}); throw e; }
}

async function removePageIfGenerated(cfg, slug) {
    const { dir, file } = pagePaths(cfg, slug);
    const html = await readIfExists(file);
    if (html === null) return { status: 'unchanged', reason: 'no-page' };
    if (!core.looksGenerated(html)) return { status: 'skipped', reason: 'not-a-generated-page' };
    await fs.unlink(file);
    await fs.rmdir(dir).catch(() => {}); // an empty folder would make nginx answer 403 instead of falling back to the app
    return { status: 'removed' };
}

// ── rendering one article ───────────────────────────────────────────────────────────────────────────────
async function renderPage(cfg, template, article, { timeoutMs = 6000 } = {}) {
    const image = core.pickImage(article);
    const dims = image.source === 'default' ? null : await core.probeImageDimensions(image.url, { allowHosts: cfg.imageHosts, cache: dimsCache, timeoutMs });
    const opts = dims ? { dims } : {};
    const html = core.renderArticleHtml(template, article, opts);
    const problems = core.verifyRendered(html, article, opts);
    if (problems.length) throw new Error(`Rendered page failed verification (${problems.join(', ')})`);
    return html;
}

async function writeArticlePage(cfg, article) {
    const { file } = pagePaths(cfg, article.slug);
    const template = await fs.readFile(cfg.templatePath, 'utf8');
    const html = await renderPage(cfg, template, article);
    const existing = await readIfExists(file);
    if (existing === html) return { status: 'unchanged' };
    await writeAtomic(file, html);
    const back = await fs.readFile(file, 'utf8');             // never claim success without looking
    if (back !== html) throw new Error('Page was written but reading it back did not match');
    return { status: 'updated' };
}

// ── public API ──────────────────────────────────────────────────────────────────────────────────────────
/**
 * Bring ONE article's public page in line with its saved state.
 *   article      the article row AFTER a successful database save (for deletes pass { ...row, status:'deleted' })
 *   previousSlug slug before this save (slug-change handling)
 *   db           supabase client (only used to check whether an old slug is now used by another article)
 * Always resolves to { status: 'updated'|'unchanged'|'removed'|'skipped'|'failed', ... } — never throws.
 */
function syncArticle(article, { previousSlug = null, deleted = false, db = null, cfg = getConfig() } = {}) {
    if (!cfg.enabled) return Promise.resolve({ status: 'skipped', reason: 'not-configured' });
    return withLock(async () => {
        const slug = article && article.slug;
        try {
            const visible = !deleted && core.isPubliclyVisible(article);
            const actions = [];
            let main;
            if (visible && !core.isValidSlug(slug)) {
                // Legacy row without a usable slug: there is no page address to write. Report it honestly (not a failure, not success).
                return { status: 'skipped', slug, reason: 'invalid-slug', actions: [] };
            }
            if (visible) {
                main = await writeArticlePage(cfg, article);
                if (main.status === 'updated') actions.push(`updated /blogs/${slug}/`);
            } else if (core.isValidSlug(slug)) {
                main = await removePageIfGenerated(cfg, slug);
                if (main.status === 'removed') actions.push(`removed /blogs/${slug}/`);
            } else {
                main = { status: 'unchanged', reason: 'no-valid-slug' };
            }
            let status = main.status;

            if (previousSlug && previousSlug !== slug && core.isValidSlug(previousSlug)) {
                let inUse = false;
                if (db) {
                    const { data } = await db.from('blogs').select('id').eq('slug', previousSlug).neq('id', article.id).limit(1);
                    inUse = !!(data && data.length);
                }
                if (!inUse) {
                    const { file } = pagePaths(cfg, previousSlug);
                    if (visible && core.isValidSlug(slug)) {
                        const stub = core.renderRedirectStub(previousSlug, slug);
                        if ((await readIfExists(file)) !== stub) { await writeAtomic(file, stub); actions.push(`redirect left at /blogs/${previousSlug}/`); }
                    } else {
                        const r = await removePageIfGenerated(cfg, previousSlug);
                        if (r.status === 'removed') actions.push(`removed old /blogs/${previousSlug}/`);
                    }
                    if (actions.length && status === 'unchanged') status = 'updated';
                }
            }
            failures.delete(slug);
            return { status, slug, actions };
        } catch (err) {
            const message = friendlyError(err);
            failures.set(slug || '(unknown)', { error: message, at: new Date().toISOString() });
            console.error(`[prerender] FAILED for "${slug}":`, err && err.message);
            return { status: 'failed', slug, message };
        }
    });
}

/** Compare every article with its page and repair differences. dryRun:true changes nothing and reports the plan. */
function reconcileAll({ db, dryRun = false, cfg = getConfig() } = {}) {
    if (!cfg.enabled) return Promise.resolve({ status: 'skipped', reason: 'not-configured' });
    return withLock(async () => {
        const started = Date.now();
        const summary = { status: 'ok', dryRun, checked: 0, updated: [], unchanged: 0, removed: [], failed: [], skipped: [] };
        const { data: rows, error } = await db.from('blogs').select('*').limit(5000);
        if (error) throw new Error(`Could not read articles: ${error.message}`);
        const articles = rows || [];
        const visible = articles.filter((a) => core.isPubliclyVisible(a));
        const visibleSlugs = new Set(visible.map((a) => a.slug));
        const template = await fs.readFile(cfg.templatePath, 'utf8');

        for (const a of visible) {
            summary.checked++;
            try {
                if (!core.isValidSlug(a.slug)) { summary.skipped.push({ slug: a.slug, reason: 'invalid-slug' }); continue; }
                const { file } = pagePaths(cfg, a.slug);
                const html = await renderPage(cfg, template, a);
                const existing = await readIfExists(file);
                if (existing === html) { summary.unchanged++; failures.delete(a.slug); continue; }
                if (!dryRun) {
                    await writeAtomic(file, html);
                    if ((await fs.readFile(file, 'utf8')) !== html) throw new Error('Page was written but reading it back did not match');
                }
                summary.updated.push(a.slug); failures.delete(a.slug);
            } catch (err) {
                summary.failed.push({ slug: a.slug, error: friendlyError(err) });
                failures.set(a.slug, { error: friendlyError(err), at: new Date().toISOString() });
                console.error(`[prerender] reconcile FAILED for "${a.slug}":`, err && err.message);
            }
        }

        // Pages whose article is no longer public (unpublished/deleted): remove — only generated pages, never when the read looked empty.
        if (articles.length > 0) {
            const blogsDir = path.join(cfg.root, 'blogs');
            let names = [];
            try { names = await fs.readdir(blogsDir); } catch (e) { if (e.code !== 'ENOENT') throw e; }
            for (const name of names) {
                if (visibleSlugs.has(name) || !core.isValidSlug(name)) continue;
                try {
                    const html = await readIfExists(path.join(blogsDir, name, 'index.html'));
                    if (html === null || !core.looksGenerated(html) || core.isRedirectStub(html)) continue;
                    if (!dryRun) await removePageIfGenerated(cfg, name);
                    summary.removed.push(name);
                } catch (err) {
                    summary.failed.push({ slug: name, error: friendlyError(err) });
                }
            }
        }
        summary.status = summary.failed.length ? 'partial' : 'ok';
        summary.finishedAt = new Date().toISOString(); summary.ms = Date.now() - started;
        if (!dryRun) lastSync = summary;
        return summary;
    });
}

/** Render one article page on request (crawler route). Short probe timeout; sizes are cached after the first read. */
function renderArticleOnDemand(template, article) {
    return renderPage(getConfig(), template, article, { timeoutMs: 1500 });
}

async function checkAccess(cfg = getConfig()) {
    const out = { enabled: cfg.enabled, root: cfg.root, templateReadable: null, rootWritable: null, blogsDirExists: null };
    if (!cfg.enabled) return out;
    try { await fs.access(cfg.templatePath, 1 << 2 /* R_OK */); out.templateReadable = true; } catch { out.templateReadable = false; }
    try { await fs.access(cfg.root, 1 << 1 /* W_OK */); out.rootWritable = true; } catch { out.rootWritable = false; }
    try { const s = await fs.stat(path.join(cfg.root, 'blogs')); out.blogsDirExists = s.isDirectory(); } catch { out.blogsDirExists = false; }
    if (out.blogsDirExists) { try { await fs.access(path.join(cfg.root, 'blogs'), 1 << 1); out.blogsDirWritable = true; } catch { out.blogsDirWritable = false; } }
    return out;
}

async function getStatus(cfg = getConfig()) {
    return {
        access: await checkAccess(cfg),
        sweepRunning: !!sweepTimer,
        lastSync: lastSync && { at: lastSync.finishedAt, status: lastSync.status, checked: lastSync.checked, updated: lastSync.updated.length, unchanged: lastSync.unchanged, removed: lastSync.removed.length, failed: lastSync.failed },
        pendingFailures: [...failures].map(([slug, v]) => ({ slug, ...v })),
    };
}

/** Timer that keeps pages in step (retries failures, publishes scheduled articles when due). Safe to call once at boot. */
function startSweep(db, { minutes = 15, firstRunDelayMs = 30000, cfg = getConfig() } = {}) {
    if (!cfg.enabled || sweepTimer || !(minutes > 0)) return false;
    const run = async () => {
        if (sweeping) return;
        sweeping = true;
        try {
            const r = await reconcileAll({ db, cfg });
            if (r.updated && (r.updated.length || r.removed.length || r.failed.length)) console.log(`[prerender] sweep: ${r.updated.length} updated, ${r.removed.length} removed, ${r.failed.length} failed`);
        } catch (err) { console.error('[prerender] sweep failed:', err && err.message); }
        finally { sweeping = false; }
    };
    const first = setTimeout(run, firstRunDelayMs); if (first.unref) first.unref();
    sweepTimer = setInterval(run, minutes * 60 * 1000); if (sweepTimer.unref) sweepTimer.unref();
    console.log(`[prerender] enabled: public site root ${cfg.root}; sweep every ${minutes} min`);
    return true;
}

function _resetForTests() { dimsCache.clear(); failures.clear(); lastSync = null; if (sweepTimer) clearInterval(sweepTimer); sweepTimer = null; sweeping = false; chain = Promise.resolve(); }

module.exports = { getConfig, renderArticleOnDemand, syncArticle, reconcileAll, checkAccess, getStatus, startSweep, friendlyError, _resetForTests };
